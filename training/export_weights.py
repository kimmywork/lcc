#!/usr/bin/env python3
"""Export PyTorch model weights as C float arrays for the WASM core."""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import torch


def emit(name: str, arr: np.ndarray, lines: list[str]) -> None:
    flat = np.asarray(arr, dtype=np.float32).reshape(-1)
    lines.append(f"static const float {name}[{flat.size}] = {{")
    for i in range(0, flat.size, 8):
        chunk = ", ".join(f"{float(v):.8g}f" for v in flat[i : i + 8])
        lines.append(f"  {chunk},")
    lines.append("};")
    lines.append("")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sr", default="training/models/sr.pt")
    ap.add_argument("--finder", default="training/models/finder32.pt")
    ap.add_argument("--out", default="native/model_weights.h")
    args = ap.parse_args()

    lines = [
        "/* Generated by training/export_weights.py. Do not edit by hand. */",
        "#ifndef LCC_MODEL_WEIGHTS_H",
        "#define LCC_MODEL_WEIGHTS_H",
        "",
    ]

    sr = torch.load(args.sr, map_location="cpu", weights_only=False)
    lines += [
        f"#define LCC_SR_WIDTH {int(sr['width'])}",
        f"#define LCC_SR_GRID {int(sr['grid'])}",
        f"#define LCC_SR_TARGET {int(sr['target'])}",
        "",
    ]
    for name, key in [
        ("LCC_SR_C1_W", "c1.weight"), ("LCC_SR_C1_B", "c1.bias"),
        ("LCC_SR_C2_W", "c2.weight"), ("LCC_SR_C2_B", "c2.bias"),
        ("LCC_SR_C3_W", "c3.weight"), ("LCC_SR_C3_B", "c3.bias"),
        ("LCC_SR_C4_W", "c4.weight"), ("LCC_SR_C4_B", "c4.bias"),
    ]:
        emit(name, sr["state_dict"][key].detach().cpu().numpy(), lines)

    fd = torch.load(args.finder, map_location="cpu", weights_only=False)
    lines += [
        f"#define LCC_FINDER_INPUT {int(fd['input'])}",
        f"#define LCC_FINDER_STRIDE {int(fd['stride'])}",
        f"#define LCC_FINDER_WIDTH {int(fd['width'])}",
        "",
    ]
    for name, key in [
        ("LCC_FINDER_C1_W", "c1.weight"), ("LCC_FINDER_C1_B", "c1.bias"),
        ("LCC_FINDER_C2_W", "c2.weight"), ("LCC_FINDER_C2_B", "c2.bias"),
        ("LCC_FINDER_C3_W", "c3.weight"), ("LCC_FINDER_C3_B", "c3.bias"),
        ("LCC_FINDER_C4_W", "c4.weight"), ("LCC_FINDER_C4_B", "c4.bias"),
        ("LCC_FINDER_C5_W", "c5.weight"), ("LCC_FINDER_C5_B", "c5.bias"),
        ("LCC_FINDER_C6_W", "c6.weight"), ("LCC_FINDER_C6_B", "c6.bias"),
    ]:
        emit(name, fd["state_dict"][key].detach().cpu().numpy(), lines)

    lines.append("#endif")
    out = Path(args.out)
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({out.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
