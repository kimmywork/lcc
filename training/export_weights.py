#!/usr/bin/env python3
"""Export the C shape-classifier weights as C float arrays."""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import torch


def emit(name: str, arr: np.ndarray, lines: list[str]) -> None:
    flat = np.asarray(arr, dtype=np.float32).reshape(-1)
    lines.append(f"static const float {name}[{flat.size}] = {{")
    for i in range(0, flat.size, 8):
        chunk = ", ".join(f"{float(v):.8e}f" for v in flat[i : i + 8])
        lines.append(f"  {chunk},")
    lines.append("};")
    lines.append("")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--shape", default="training/models/shape_cls8_combined.pt")
    ap.add_argument("--out", default="native/model_weights.h")
    args = ap.parse_args()

    ck = torch.load(args.shape, map_location="cpu", weights_only=False)
    sd = ck["state_dict"]
    lines = [
        "/* Generated by training/export_weights.py. Do not edit by hand. */",
        "#ifndef LCC_MODEL_WEIGHTS_H",
        "#define LCC_MODEL_WEIGHTS_H",
        "",
        f"#define LCC_SHAPE_WIDTH {int(ck['width'])}",
        f"#define LCC_SHAPE_GRID {int(ck['grid'])}",
        "",
    ]
    for name, key in [
        ("LCC_SHAPE_C1_W", "c1.weight"), ("LCC_SHAPE_C1_B", "c1.bias"),
        ("LCC_SHAPE_C2_W", "c2.weight"), ("LCC_SHAPE_C2_B", "c2.bias"),
        ("LCC_SHAPE_C3_W", "c3.weight"), ("LCC_SHAPE_C3_B", "c3.bias"),
        ("LCC_SHAPE_FC_W", "fc.weight"), ("LCC_SHAPE_FC_B", "fc.bias"),
    ]:
        emit(name, sd[key].detach().cpu().numpy(), lines)
    lines.append("#endif")
    out = Path(args.out)
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({out.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
