/**
 * Emit the JS palette tables the C decoder classifies against.
 * Run before the WASM build so nominal colours match the encoder.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { LAYERS } from '../src/constants.js';
import { generatePalette } from '../src/palettes.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outPath = path.join(root, 'native', 'palette_tables.c');

function f64(n) {
  if (!Number.isFinite(n)) return '0.0';
  return n.toExponential(16);
}

function bytes(list) {
  const flat = [];
  for (const rgb of list) flat.push(rgb[0], rgb[1], rgb[2]);
  return flat.join(', ');
}

function labs(list) {
  const flat = [];
  for (const lab of list) flat.push(f64(lab[0]), f64(lab[1]), f64(lab[2]));
  return flat.join(', ');
}

const chunks = [];
const entries = [];
chunks.push(`/* Generated by scripts/gen-palette-tables.js. Do not edit. */`);
chunks.push(`#include "lcc.h"`);
chunks.push(``);

for (const name of Object.keys(LAYERS)) {
  const layer = LAYERS[name];
  for (const harmony of layer.kind === 'gray' ? [false] : [false, true]) {
    const palette = generatePalette(name, { mode: 'maxmin', harmony });
    const id = `${name}_${harmony ? 1 : 0}`;
    chunks.push(`static const uint8_t rgb_${id}[] = { ${bytes(palette.palette)} };`);
    chunks.push(`static const double lab_${id}[] = { ${labs(palette.paletteLab)} };`);
    chunks.push(`static const uint8_t gray_${id}[] = { ${bytes(palette.grayPalette)} };`);
    chunks.push(`static const double graylab_${id}[] = { ${labs(palette.grayLab)} };`);
    chunks.push(`static const int16_t rank_${id}[] = { ${Array.from(palette.rankOf).join(', ')} };`);
    entries.push(`  { "${name}", ${harmony ? 1 : 0}, ${layer.kind === 'gray' ? 0 : 1}, ${layer.levels ?? 0}, ${palette.palette.length}, ${layer.bitsPerModule}, ${layer.shapeSetSize ?? 0}, ${layer.shapeLayerId ?? -1}, ${layer.shapeExt ?? 0}, ${palette.blackIndex}, ${palette.whiteIndex}, ${palette.rankCount}, ${palette.maxRankDiff}, ${palette.initialRank}, ${f64(palette.minDeltaE)}, rgb_${id}, lab_${id}, gray_${id}, graylab_${id}, rank_${id} },`);
  }
}

chunks.push(``);
chunks.push(`const LccPaletteInfo lcc_palettes[] = {`);
chunks.push(entries.join('\n'));
chunks.push(`};`);
chunks.push(`const int lcc_palette_count = ${entries.length};`);
chunks.push(``);

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, chunks.join('\n'));
console.log(`wrote ${outPath} (${entries.length} palettes)`);
